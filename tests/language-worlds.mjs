import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = file => readFileSync(new URL(`../${file}`, import.meta.url), "utf8");
const manifest = JSON.parse(read("manifest.json"));
const worlds = new Map();
for (const group of manifest.content_scripts) {
  for (const file of group.js) {
    const world = group.world || "ISOLATED";
    if (worlds.has(file)) assert.equal(worlds.get(file), world, `${file} must use a distinct entry point in each world`);
    worlds.set(file, world);
  }
}
assert.equal(worlds.get("page-language.js"), "MAIN");
assert.equal(worlds.get("language.js"), "ISOLATED");
assert.equal(read("page-language.js"), "// Generated by scripts/build-page-language.mjs from language.js and language-ui.js.\n" + [read("language.js"), read("language-ui.js")].join("\n"));
console.log("PASS: distinct language entry points for MAIN and ISOLATED, generated translations match their sources");
